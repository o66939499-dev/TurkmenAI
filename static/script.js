const symbols = {
  Turkmen: "TK",
  Turkish: "TR",
  Azerbaijani: "AZ",
  English: "EN",
  Russian: "RU",
  Uncertain: "?"
};

const elements = {
  input: document.getElementById("textInput"),
  count: document.getElementById("charCount"),
  analyze: document.getElementById("analyzeBtn"),
  buttonText: document.getElementById("buttonText"),
  clear: document.getElementById("clearBtn"),
  error: document.getElementById("errorBox"),
  result: document.getElementById("result"),
  language: document.getElementById("languageResult"),
  symbol: document.getElementById("languageSymbol"),
  confidence: document.getElementById("confidenceValue"),
  bar: document.getElementById("confidenceBar"),
  status: document.getElementById("statusText"),
  badge: document.getElementById("statusBadge"),
  time: document.getElementById("resultTime"),
  selector: document.getElementById("languageSelect"),
  theme: document.getElementById("themeToggle"),
  themeIcon: document.getElementById("themeIcon")
};

let currentLanguage = "tk";

function t(key) {
  return translations[currentLanguage][key] ||
         translations.en[key] ||
         key;
}

function updateInterface() {
  document.documentElement.lang = currentLanguage;

  document.querySelectorAll("[data-i18n]").forEach(element => {
    const key = element.dataset.i18n;
    if (translations[currentLanguage][key]) {
      element.textContent = t(key);
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach(element => {
    const key = element.dataset.i18nPlaceholder;
    element.placeholder = t(key);
  });

  elements.count.textContent =
    `${elements.input.value.length} / 5000`;
}

elements.selector.addEventListener("change", event => {
  currentLanguage = event.target.value;
  updateInterface();
  elements.result.classList.add("hidden");
  elements.error.classList.add("hidden");
});

function setTheme(theme) {
  document.body.classList.toggle("light", theme === "light");
  elements.themeIcon.textContent =
    theme === "light" ? "☾" : "☀";

  try {
    localStorage.setItem("turkmenai-theme", theme);
  } catch (_) {}
}

let savedTheme = "dark";

try {
  savedTheme = localStorage.getItem("turkmenai-theme") || "dark";
} catch (_) {}

setTheme(savedTheme);

elements.theme.addEventListener("click", () => {
  const newTheme = document.body.classList.contains("light")
    ? "dark"
    : "light";

  setTheme(newTheme);
});

elements.input.addEventListener("input", () => {
  elements.count.textContent =
    `${elements.input.value.length} / 5000`;

  elements.error.classList.add("hidden");
});

elements.clear.addEventListener("click", () => {
  elements.input.value = "";
  elements.count.textContent = "0 / 5000";
  elements.result.classList.add("hidden");
  elements.error.classList.add("hidden");
  elements.input.focus();
});

function showError(message) {
  elements.error.textContent = message;
  elements.error.classList.remove("hidden");
}

function getLanguageName(language) {
  if (language === "Uncertain") {
    return languageNames.Uncertain[currentLanguage];
  }

  return languageNames[language] || language;
}

function showResult(data) {
  const confidence = Number(data.confidence);

  if (!Number.isFinite(confidence) ||
      confidence < 0 || confidence > 100) {
    throw new Error("Invalid confidence value from server.");
  }

  const language = data.language || "Uncertain";
  const isUncertain = language === "Uncertain";

  elements.language.textContent = getLanguageName(language);
  elements.symbol.textContent = symbols[language] || "AI";
  elements.confidence.textContent = `${confidence.toFixed(2)}%`;

  elements.bar.style.width = `${confidence}%`;

  let badgeClass = "low";
  let badgeText = t("low");
  let statusText = t("lowStatus");

  if (isUncertain) {
    badgeText = t("uncertain");
    statusText = t("short");
  } else if (confidence >= 90) {
    badgeClass = "";
    badgeText = t("high");
    statusText = t("highStatus");
  } else if (confidence >= 70) {
    badgeClass = "medium";
    badgeText = t("medium");
    statusText = t("mediumStatus");
  }

  if (data.status === "Please provide a longer sentence.") {
    statusText = t("short");
  } else if (data.status === "Low confidence — verify the result.") {
    statusText = t("lowStatus");
  } else if (data.status === "Medium confidence.") {
    statusText = t("mediumStatus");
  } else if (data.status === "High confidence.") {
    statusText = t("highStatus");
  }

  if (data.suggestion && isUncertain) {
    statusText += " " + getLanguageName(data.suggestion) + ".";
  }

  elements.badge.className = `result-badge ${badgeClass}`;
  elements.badge.textContent = badgeText;
  elements.status.textContent = statusText;
  elements.time.textContent =
    new Date().toLocaleTimeString();

  elements.result.classList.remove("hidden");
}

async function analyzeText() {
  const text = elements.input.value.trim();

  elements.error.classList.add("hidden");
  elements.result.classList.add("hidden");

  if (!text) {
    showError(t("empty"));
    elements.input.focus();
    return;
  }

  if (text.length > 5000) {
    showError(t("tooLong"));
    return;
  }

  elements.analyze.disabled = true;
  elements.buttonText.textContent = t("analyzing");

  try {
    const response = await fetch("/predict", {
      method: "POST",
      headers: {
        "Content-Type": "application/json"
      },
      body: JSON.stringify({ text })
    });

    const data = await response.json().catch(() => ({}));

    if (!response.ok) {
      throw new Error(data.error || t("network"));
    }

    showResult(data);

  } catch (error) {
    showError(error.message || t("network"));

  } finally {
    elements.analyze.disabled = false;
    elements.buttonText.textContent = t("analyze");
  }
}

elements.analyze.addEventListener("click", analyzeText);

elements.input.addEventListener("keydown", event => {
  if (event.ctrlKey && event.key === "Enter") {
    event.preventDefault();
    analyzeText();
  }
});

updateInterface();

console.log("TurkmenAI Frontend initialized successfully.");
